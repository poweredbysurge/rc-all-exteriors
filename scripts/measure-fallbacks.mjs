#!/usr/bin/env node
// Measures metric-matched fallback faces for the two self-hosted fonts and
// writes src/styles/fonts.css.
//
// "Measured on the rendered case" (master prompt section 2): the size-adjust
// is the ratio of real advance widths over the site's own copy, set the way
// it renders. Headings are sentence case in Archivo Expanded 700, so the
// sample is every heading in copy/ lowercased after its first letter.
// Paragraphs are Manrope 400. A generic xAvgCharWidth ratio is off by several
// percent for an expanded face, which is where font-swap CLS comes from.
//
// Fallback faces are Arial Bold and Arial (present on macOS, Windows and iOS).
// Android has no Arial; it falls through to the system sans, which is close
// enough at these ratios that the swap stays under the CLS budget.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import * as fontkit from 'fontkit';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const copy = readdirSync(join(root, 'copy'))
  .filter((f) => /^batch-\d+\.md$/.test(f))
  .map((f) => readFileSync(join(root, 'copy', f), 'utf8'))
  .join('\n');

const grab = (tags) =>
  [...copy.matchAll(new RegExp(`^\\**\\[(?:${tags})\\]\\**\\s+(.+)$`, 'gm'))]
    .map((m) => m[1].replace(/\[CONFIRM[^\]]*\]/g, '').replace(/\[LINK\].*$/, '').replace(/[*\\]/g, '').trim())
    .filter(Boolean);

const headings = grab('H1|H2|H3').map((s) => s[0] + s.slice(1).toLowerCase());
const paragraphs = grab('P|SUBHEAD|FAQ A');

// Widths are measured in headless Chrome with the real font files, so shaping,
// kerning and the variable weight instance are exactly what a visitor gets.
import puppeteer from 'puppeteer-core';

const CHROME = process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const b64 = (f) => readFileSync(join(root, f)).toString('base64');

const browser = await puppeteer.launch({ executablePath: CHROME, headless: true });
const page = await browser.newPage();
await page.setContent(`<!doctype html><style>
@font-face{font-family:"A";font-weight:700;font-stretch:125%;src:url(data:font/woff2;base64,${b64('public/fonts/archivo-expanded-700-latin.woff2')}) format("woff2");}
@font-face{font-family:"M";font-weight:400 700;src:url(data:font/woff2;base64,${b64('public/fonts/manrope-variable-latin.woff2')}) format("woff2");}
span{position:absolute;white-space:nowrap;font-size:100px;line-height:1;}
</style><body></body>`);
await page.evaluate(() => Promise.all([document.fonts.load('700 100px "A"'), document.fonts.load('400 100px "M"')]));

async function ratio(samples, primary, fallback) {
  return page.evaluate(
    (samples, primary, fallback) => {
      const measure = (css) => {
        let sum = 0;
        for (const text of samples) {
          const el = document.createElement('span');
          el.style.cssText = css;
          el.textContent = text;
          document.body.appendChild(el);
          sum += el.getBoundingClientRect().width;
          el.remove();
        }
        return sum;
      };
      return measure(primary) / measure(fallback);
    },
    samples,
    primary,
    fallback,
  );
}

function vertical(file, sizeAdjust) {
  const font = fontkit.openSync(join(root, file));
  return {
    sizeAdjust,
    ascent: font.ascent / font.unitsPerEm / sizeAdjust,
    descent: Math.abs(font.descent) / font.unitsPerEm / sizeAdjust,
    lineGap: font.lineGap / font.unitsPerEm / sizeAdjust,
  };
}
const pct = (n) => `${(n * 100).toFixed(2)}%`;

const archivo = vertical(
  'public/fonts/archivo-expanded-700-latin.woff2',
  await ratio(
    headings,
    'font-family:"A";font-weight:700;font-stretch:125%;letter-spacing:-0.015em',
    'font-family:Arial;font-weight:700;letter-spacing:-0.015em',
  ),
);
const manrope = vertical(
  'public/fonts/manrope-variable-latin.woff2',
  await ratio(paragraphs, 'font-family:"M";font-weight:400', 'font-family:Arial;font-weight:400'),
);
await browser.close();

const RANGE =
  'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD';

const css = `/* GENERATED by scripts/measure-fallbacks.mjs. Do not edit by hand.
   Archivo: Expanded (wdth 125) 700, the only instance the site renders, Latin subset.
   Manrope: variable wght, used at 400 / 500 / 600 / 700, Latin subset.
   Fallback metrics measured over ${headings.length} headings and ${paragraphs.length} paragraphs from copy/. */
@font-face {
  font-family: "Archivo";
  font-style: normal;
  font-weight: 700;
  font-stretch: 125%;
  font-display: swap;
  src: url("/fonts/archivo-expanded-700-latin.woff2") format("woff2");
  unicode-range: ${RANGE};
}
@font-face {
  font-family: "Manrope";
  font-style: normal;
  font-weight: 400 700;
  font-display: swap;
  src: url("/fonts/manrope-variable-latin.woff2") format("woff2");
  unicode-range: ${RANGE};
}
@font-face {
  font-family: "Archivo Fallback";
  font-weight: 700;
  src: local("Arial Bold"), local("Arial-BoldMT"), local("Arial");
  size-adjust: ${pct(archivo.sizeAdjust)};
  ascent-override: ${pct(archivo.ascent)};
  descent-override: ${pct(archivo.descent)};
  line-gap-override: ${pct(archivo.lineGap)};
}
@font-face {
  font-family: "Manrope Fallback";
  src: local("Arial"), local("ArialMT");
  size-adjust: ${pct(manrope.sizeAdjust)};
  ascent-override: ${pct(manrope.ascent)};
  descent-override: ${pct(manrope.descent)};
  line-gap-override: ${pct(manrope.lineGap)};
}
`;

writeFileSync(join(root, 'src/styles/fonts.css'), css);
console.log('Archivo Expanded 700 vs Arial Bold:', archivo);
console.log('Manrope 400 vs Arial:', manrope);
console.log('wrote src/styles/fonts.css');
